"""Run every case in docs/test_cases.csv against the API.

Writes docs/test_results.csv and docs/test_table.md (ready for the report/PPT)
and prints a summary. Failures are kept in, on purpose.
Run: python tests/e2e/run_cases.py [--base http://localhost:8000]
     (without a running server it uses the app in-process)
"""

from __future__ import annotations

import argparse
import csv
import json
import time
from pathlib import Path
from typing import Any

import httpx

ROOT = Path(__file__).resolve().parents[2]
CASES = ROOT / "docs" / "test_cases.csv"
RESULTS = ROOT / "docs" / "test_results.csv"
TABLE = ROOT / "docs" / "test_table.md"


def client(base: str) -> Any:
    try:
        httpx.get(f"{base}/api/v1/health", timeout=2).raise_for_status()
        return httpx.Client(base_url=base, timeout=15)
    except httpx.HTTPError:
        from fastapi.testclient import TestClient

        from backend.app.main import app

        print("(no server at --base; running the app in-process)")
        return TestClient(app).__enter__()


def call(c: Any, case: dict[str, str]) -> tuple[int, dict[str, Any]]:
    if case["kind"] == "transaction":
        body = {"transaction": json.loads(case["input"]), "lang_out": "en"}
        r = c.post("/api/v1/analyze/transaction", json=body)
    else:
        body = {"text": case["input"], "channel": case["channel"] or "sms", "sender": case["sender"] or None, "lang_out": "en"}
        r = c.post("/api/v1/analyze/message", json=body)
    return r.status_code, (r.json() if r.headers.get("content-type", "").startswith("application/json") else {})


def evaluate(case: dict[str, str], status: int, data: dict[str, Any]) -> dict[str, Any]:
    expected = case["expected_label"].split("|")
    actual = data.get("label", str(status)) if status == 200 else str(status)
    fired = {s["code"] for s in data.get("signals", [])}
    want = {s for s in case["expected_signals"].split(";") if s}
    return {
        "actual": actual, "score": data.get("risk_score", ""), "passed": actual in expected and status != 500,
        "signals_ok": want <= fired, "fired": ";".join(sorted(fired)), "missing": ";".join(sorted(want - fired)),
    }


def summarise_input(case: dict[str, str]) -> str:
    if case["kind"] == "transaction":
        t = json.loads(case["input"])
        return f"{t['user_id']} {t['type']} ₹{t['amount_inr']:,} to {t['payee_name']}"
    text = case["input"].replace("|", "/")
    return (text[:70] + "…") if len(text) > 70 else (text or "(empty)")


def write_outputs(rows: list[dict[str, Any]]) -> None:
    cols = ["id", "category", "expected", "actual", "score", "pass", "signals_ok", "missing_signals", "latency_ms"]
    with RESULTS.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=cols)
        w.writeheader()
        for r in rows:
            w.writerow({k: r[k] for k in cols})
    lines = ["| ID | Category | Input (summary) | Expected | Actual | Score | Result | Note |", "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        note = r["why"] if r["pass"] else f"FAIL. {r['why']}"
        if r["pass"] and r["signals_ok"] != "yes":
            note += f" (missing signal: {r['missing_signals']})"
        lines.append(f"| {r['id']} | {r['category']} | {r['summary']} | {r['expected']} | {r['actual']} | {r['score']} | {'✅ pass' if r['pass'] else '❌ fail'} | {note} |")
    TABLE.write_text("# Test case results\n\nGenerated by `make e2e` from `docs/test_cases.csv`. Failures are kept in on purpose.\n\n" + "\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", default="http://localhost:8000")
    args = ap.parse_args()
    c = client(args.base)
    rows = []
    with CASES.open(encoding="utf-8") as f:
        for case in csv.DictReader(f):
            t0 = time.perf_counter()
            status, data = call(c, case)
            latency = round((time.perf_counter() - t0) * 1000, 1)
            res = evaluate(case, status, data)
            rows.append({"id": case["id"], "category": case["category"], "expected": case["expected_label"], "actual": res["actual"],
                         "score": res["score"], "pass": res["passed"], "signals_ok": "yes" if res["signals_ok"] else "no",
                         "missing_signals": res["missing"], "latency_ms": latency, "why": case["why"], "summary": summarise_input(case)})
    write_outputs(rows)
    passed = sum(r["pass"] for r in rows)
    sig = sum(r["signals_ok"] == "yes" for r in rows)
    print(f"{passed}/{len(rows)} cases pass on label · {sig}/{len(rows)} have all expected signals · "
          f"median latency {sorted(r['latency_ms'] for r in rows)[len(rows) // 2]} ms")
    for r in rows:
        if not r["pass"] or r["signals_ok"] != "yes":
            print(f"  {r['id']:4} {r['category']:32} expected {r['expected']:22} got {r['actual']:10} {r['score']!s:>4}  missing: {r['missing_signals'] or '-'}")
    print(f"wrote {RESULTS.relative_to(ROOT)} and {TABLE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
